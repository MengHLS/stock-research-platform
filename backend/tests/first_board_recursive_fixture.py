def rewrite_json(root: Path, name: str, mutator) -> None:
    path = root / name
    value = json.loads(path.read_text(encoding="utf-8"))
    mutator(value)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")


def rewrite_rows(root: Path, name: str, mutator) -> None:
    path = root / name
    fields = {
        "target-chain-summary.csv": TARGET_FIELDS,
        "candidate-links.csv.gz": CANDIDATE_FIELDS,
        "detected-firstboards.csv.gz": DETECTED_FIELDS,
    }[name]
    if path.suffix == ".gz":
        with gzip.open(path, "rt", encoding="utf-8", newline="") as handle:
            rows = list(csv.DictReader(handle))
    else:
        with path.open("r", encoding="utf-8", newline="") as handle:
            rows = list(csv.DictReader(handle))
    mutator(rows)
    _write_csv(path, fields, rows)
